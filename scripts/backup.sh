#!/usr/bin/env bash
# Back up the app's data volume (uploads + Chroma) to a tar.gz, upload it to
# S3 (LocalStack), and keep the newest $KEEP_LOCAL copies locally.
#
# Usage: scripts/backup.sh
# Cron:  0 2 * * * /opt/ultradoc/app/scripts/backup.sh >> /opt/ultradoc/logs/backup.log 2>&1
set -euo pipefail

export SCRIPT_NAME=backup
# shellcheck source-path=SCRIPTDIR source=lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib/common.sh"

: "${KEEP_LOCAL:=7}"

require_cmd docker aws flock sha256sum

mkdir -p "$BACKUP_DIR"

# Never run two backups at once (e.g. a slow one overlapping the next cron run).
exec 9>"$BACKUP_DIR/.backup.lock"
flock -n 9 || die "another backup is already running"

docker volume inspect "$DATA_VOLUME" >/dev/null 2>&1 || die "volume $DATA_VOLUME not found"
# Pull the helper image now, not while the API is paused.
docker image inspect "$HELPER_IMAGE" >/dev/null 2>&1 || docker pull -q "$HELPER_IMAGE" >/dev/null

stamp="$(date -u +%Y%m%dT%H%M%SZ)"
archive="$BACKUP_DIR/${NAME_PREFIX}-data-${stamp}.tar.gz"
partial="$archive.partial"

# Pause the API while tar reads the volume, so Chroma's SQLite files aren't
# captured mid-write. Pausing (not stopping) keeps it to a few seconds and
# open connections survive. The trap guarantees it is always unpaused.
paused=false
unpause() {
  if [[ "$paused" == true ]]; then
    docker unpause "$API_CONTAINER" >/dev/null && log "unpaused $API_CONTAINER"
  fi
  rm -f "$partial"
}
trap unpause EXIT

if [[ "$(docker inspect -f '{{.State.Running}}' "$API_CONTAINER" 2>/dev/null)" == "true" ]]; then
  docker pause "$API_CONTAINER" >/dev/null
  paused=true
  log "paused $API_CONTAINER for a consistent snapshot"
fi

log "archiving volume $DATA_VOLUME"
# Stream the archive out on stdout: no host bind mounts, so this works the
# same on the VM, in WSL, or inside another container.
docker run --rm -v "$DATA_VOLUME":/data:ro "$HELPER_IMAGE" \
  tar -czf - --numeric-owner -C /data . >"$partial"

docker unpause "$API_CONTAINER" >/dev/null
paused=false
log "unpaused $API_CONTAINER"
# Docker flags a paused container "unhealthy" until its next probe passes;
# wait for that so monitoring doesn't see a false alarm after every backup.
wait_healthy "$API_CONTAINER" 60 || log "warning: $API_CONTAINER not healthy yet after unpause"

gzip -t "$partial" || die "archive failed integrity check"
mv "$partial" "$archive"
sha256sum "$archive" | awk '{print $1}' >"$archive.sha256"
log "wrote $archive ($(du -h "$archive" | cut -f1))"

key="${S3_PREFIX}$(basename "$archive")"
s3 cp --only-show-errors "$archive" "s3://$S3_BUCKET/$key"
s3 cp --only-show-errors "$archive.sha256" "s3://$S3_BUCKET/$key.sha256"
log "uploaded s3://$S3_BUCKET/$key"

# Retention: keep the newest $KEEP_LOCAL archives (and their checksums).
# Names are generated by this script (no spaces), so ls -t is safe here.
# shellcheck disable=SC2012
mapfile -t old < <(ls -1t "$BACKUP_DIR"/"${NAME_PREFIX}"-data-*.tar.gz 2>/dev/null | tail -n +"$((KEEP_LOCAL + 1))")
for file in "${old[@]}"; do
  rm -f -- "$file" "$file.sha256"
  log "pruned $(basename "$file")"
done

log "backup complete"
